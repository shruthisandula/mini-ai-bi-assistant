import time
from typing import Dict, Any, Optional, List
from src.database import execute_query, get_schema_summary
from src.security import SQLValidator, SQLSecurityError
from src.nlp_engine import DeterministicNLPEngine
from src.llm_engine import LLMTextToSQL

class BIAssistant:
    """
    Hybrid AI Business Intelligence Assistant.
    Combines Vectorless RAG Text-to-SQL with Deterministic Intent Matching
    and strict AST/Regex security guardrails.
    """

    def __init__(self):
        self.nlp_engine = DeterministicNLPEngine()
        self.llm_engine = LLMTextToSQL()

    def ask(self, question: str) -> Dict[str, Any]:
        """
        Main query entrypoint. Processes question, generates SQL,
        validates query, executes against SQLite, and returns structured result.
        """
        start_time = time.perf_counter()

        if not question or not question.strip():
            return {
                "status": "error",
                "question": question,
                "error": "Question cannot be empty. Please ask a business question about sales data."
            }

        q = question.strip()

        # Step 1: Attempt Deterministic Engine first (ultra-fast, zero-hallucination)
        nlp_match = self.nlp_engine.parse_query(q)
        sql_candidate = None
        engine_mode = "deterministic_agent"
        meta_intent = None
        explanation = ""
        chart_type = "bar"
        x_key = None
        y_key = None

        if nlp_match:
            sql_candidate = nlp_match.get("sql")
            meta_intent = nlp_match.get("intent")
            explanation = nlp_match.get("explanation", "")
            chart_type = nlp_match.get("chart_type", "bar")
            x_key = nlp_match.get("x_key")
            y_key = nlp_match.get("y_key")
        else:
            # Step 2: Fall back to Vectorless RAG LLM Engine if available
            if self.llm_engine.is_llm_available():
                llm_res = self.llm_engine.generate_sql(q)
                if llm_res:
                    if "error" in llm_res:
                        return {
                            "status": "error",
                            "question": q,
                            "error": llm_res["error"],
                            "supported_examples": self.get_sample_questions()
                        }
                    sql_candidate = llm_res.get("sql")
                    explanation = llm_res.get("explanation", "Generated by LLM Text-to-SQL Agent.")
                    chart_type = llm_res.get("chart_type", "bar")
                    x_key = llm_res.get("x_key")
                    y_key = llm_res.get("y_key")
                    engine_mode = "vectorless_rag_llm"

        if not sql_candidate:
            return {
                "status": "error",
                "question": q,
                "error": (
                    "I could not understand your question or translate it into an authorized database query. "
                    "I specialize in sales analytics like total revenue, top products, monthly trends, regional sales, and month comparisons."
                ),
                "supported_examples": self.get_sample_questions()
            }

        # Step 3: SQL Security Guardrail Validation
        is_valid, sanitized_sql, err = SQLValidator.sanitize_and_validate(sql_candidate)
        if not is_valid:
            return {
                "status": "error",
                "question": q,
                "sql_query": sql_candidate,
                "error": f"Query Security Guardrail Rejected: {err}",
                "security_flag": True
            }

        # Step 4: Deterministic Database Execution
        try:
            columns, rows = execute_query(sanitized_sql)
        except Exception as db_err:
            return {
                "status": "error",
                "question": q,
                "sql_query": sanitized_sql,
                "error": f"Database Execution Error: {str(db_err)}"
            }

        # Step 5: Answer Formatting & Synthesis
        if meta_intent:
            answer_text = self.nlp_engine.format_answer(meta_intent, rows, nlp_match)
        else:
            answer_text = self._generic_synthesize(rows, explanation)

        # Step 6: Construct Chart Visualization Payload
        chart_config = self._build_chart_config(chart_type, columns, rows, x_key, y_key)

        elapsed = time.perf_counter() - start_time

        return {
            "status": "success",
            "question": q,
            "intent": meta_intent or "custom_query",
            "sql_query": sanitized_sql,
            "answer": answer_text,
            "explanation": explanation,
            "columns": columns,
            "rows": rows,
            "row_count": len(rows),
            "chart_config": chart_config,
            "execution_time_ms": round(elapsed * 1000, 2),
            "engine_mode": engine_mode
        }

    def _generic_synthesize(self, rows: List[Dict[str, Any]], explanation: str) -> str:
        if not rows:
            return "No matching records found in the sales database."
        if len(rows) == 1:
            row = rows[0]
            details = [f"**{k.replace('_', ' ').title()}:** {v}" for k, v in row.items()]
            return f"**Results:**\n\n" + "\n".join(f"• {d}" for d in details)
        return f"Found {len(rows)} matching results. {explanation}"

    def _build_chart_config(
        self,
        chart_type: str,
        columns: List[str],
        rows: List[Dict[str, Any]],
        x_key: Optional[str] = None,
        y_key: Optional[str] = None
    ) -> Optional[Dict[str, Any]]:
        """Constructs Chart.js compatible configuration for dynamic frontend visualization."""
        if not rows or chart_type in ("metric_card", "table") or len(columns) < 2:
            return None

        # Auto-detect keys if not explicitly provided
        if not x_key or x_key not in columns:
            x_key = columns[0]
        if not y_key or y_key not in columns:
            numeric_cols = [c for c in columns if c != x_key and any(isinstance(r.get(c), (int, float)) for r in rows)]
            y_key = numeric_cols[0] if numeric_cols else (columns[1] if len(columns) > 1 else columns[0])

        labels = [str(r.get(x_key, "")) for r in rows]
        data = [r.get(y_key, 0) for r in rows]

        return {
            "type": chart_type,
            "x_axis_label": x_key.replace("_", " ").title(),
            "y_axis_label": y_key.replace("_", " ").title(),
            "labels": labels,
            "datasets": [
                {
                    "label": y_key.replace("_", " ").title(),
                    "data": data
                }
            ]
        }

    @staticmethod
    def get_sample_questions() -> List[str]:
        return [
            "What is the total revenue?",
            "Which product generated the highest revenue?",
            "What is the monthly revenue trend?",
            "Which region generated the highest sales?",
            "How did revenue change between January and February?",
            "What is the sales breakdown by product category?",
            "Compare Online vs Retail sales channel performance",
            "Show all returned transactions"
        ]
